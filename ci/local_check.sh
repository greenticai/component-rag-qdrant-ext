#!/usr/bin/env bash
set -uo pipefail

# `src/lib.rs` declares `mod bindings;`, and `src/bindings.rs` is generated
# (gitignored) by cargo-component from wit/world.wit. On a fresh checkout it
# does not exist at all, which breaks fmt/clippy/test before any of them get
# to run: `cargo fmt` reports "failed to resolve mod `bindings`: ... does not
# exist", and clippy/test simply fail to compile. `cargo component bindings`
# regenerates just the bindings file (no wasm build, effectively instant),
# so every step below always has something to compile against.
cargo component bindings

# `cargo fmt --all -- --check` walks this crate's whole module tree
# (src/lib.rs declares `mod bindings;`), which pulls in src/bindings.rs —
# generated by wit-bindgen, gitignored, and never emitted in rustfmt's
# preferred form. Because this gate's own last step is the build, the very
# next run after a green one fails on src/bindings.rs alone: a file the
# author never wrote and cannot reformat away.
#
# Excluding it by filtering the *file list* handed to rustfmt does not work:
# stable rustfmt resolves `mod` declarations from whatever file it is given
# (there is no crate-root-only mode), so `rustfmt --check src/lib.rs` still
# opens and reports on src/bindings.rs even when it is never named on the
# command line. `rustfmt.toml`'s `ignore` key would exclude it cleanly, but
# is nightly-only. So instead: run the normal whole-crate check and filter
# *its* diff report, dropping any diff whose file is exactly src/bindings.rs
# — the only generated file this crate ever produces — and fail on anything
# else, including a cargo-fmt error unrelated to a diff at all.
fmt_output="$(cargo fmt --all -- --check 2>&1)"
fmt_status=$?
if [ "$fmt_status" -ne 0 ]; then
  diff_files="$(printf '%s\n' "$fmt_output" | sed -n 's/^Diff in \(.*\):[0-9][0-9]*:$/\1/p')"
  offenders="$(printf '%s\n' "$diff_files" | grep -v '/src/bindings\.rs$' || true)"
  if [ -z "$diff_files" ] || [ -n "$offenders" ]; then
    # Either cargo fmt failed for a reason other than a listed diff (parse
    # error, panic, ...), or a real (non-generated) file is misformatted —
    # both are the author's problem and must fail the gate.
    printf '%s\n' "$fmt_output"
    exit 1
  fi
  echo "note: cargo fmt found only generated src/bindings.rs out of format — ignoring"
fi

set -e
cargo clippy --all-targets -- -D warnings
cargo test
./build.sh
